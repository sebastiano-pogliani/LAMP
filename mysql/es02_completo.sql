CREATE DATABASE IF NOT EXISTS digital_twin;
SHOW DATABASES;
USE digital_twin;
CREATE TABLE IF NOT EXISTS sensori (id_sensore INT AUTO_INCREMENT PRIMARY KEY, tipo VARCHAR(20) NOT NULL, unita_misura VARCHAR(10) NOT NULL, posizione VARCHAR(20) NOT NULL, data_installazione DATE);
SHOW TABLES;
CREATE TABLE IF NOT EXISTS rilevazioni (id_rilevazione INT AUTO_INCREMENT PRIMARY KEY, id_sensore INT, timestamp DATETIME NOT NULL, valori DECIMAL(10, 2) NOT NULL, quantita INT NOT NULL, FOREIGN KEY (id_sensore) REFERENCES sensori(id_sensore));
SHOW TABLES;
CREATE TABLE IF NOT EXISTS allarmi (id_allarme INT AUTO_INCREMENT PRIMARY KEY, id_sensore INT, timestamp_inizio DATETIME NOT NULL, timestamp_fine DATETIME NOT NULL, livello DECIMAL(2, 1) NOT NULL, descrizione VARCHAR(100), FOREIGN KEY (id_sensore) REFERENCES sensori(id_sensore));
SHOW TABLES;
CREATE TABLE IF NOT EXISTS manutenzioni (id_manutenzione INT AUTO_INCREMENT PRIMARY KEY, id_allarme INT, tecnico VARCHAR(50), data_intervento DATE, esito VARCHAR(15), FOREIGN KEY (id_allarme) REFERENCES allarmi(id_allarme));
